// Generates tokens.css: custom properties for every token, with per-mode blocks.
import { MODES, hasModes, rawValue, MODE_CHAIN } from './load.mjs';
import { css } from './render.mjs';

const REM_ROOTS = new Set(['space', 'size', 'density', 'font', 'component']);
const PREFIX = '--ndl-';
export const cssName = (path) => PREFIX + path.split('.').join('-');

const ctxFor = (token, extra = {}) => ({
  ref: (p) => `var(${cssName(p)})`,
  rem: token.type === 'dimension' && REM_ROOTS.has(token.path.split('.')[0]),
  ...extra,
});

const decl = (token, value) => `  ${cssName(token.path)}: ${value};`;

function densityBlocks(tokens) {
  const byDensity = new Map();
  for (const t of tokens.values()) {
    const [root, name, key] = t.path.split('.');
    if (root !== 'density') continue;
    if (!byDensity.has(name)) byDensity.set(name, []);
    byDensity.get(name).push(`  ${PREFIX}density-${key}: ${css(t.value, t.type, ctxFor(t))};`);
  }
  return byDensity;
}

/** Selector wrappers that activate each mode. Order matters: later blocks win on equal specificity. */
const MODE_SELECTORS = {
  dark: [
    { at: '(prefers-color-scheme: dark)', sel: ':root:not([data-theme="light"])' },
    { sel: ':root[data-theme="dark"]' },
  ],
  'light-hc': [
    { at: '(prefers-contrast: more)', sel: ':root:not([data-theme="dark"])' },
    { sel: ':root[data-contrast="more"]:not([data-theme="dark"])' },
  ],
  'dark-hc': [
    { at: '(prefers-contrast: more) and (prefers-color-scheme: dark)', sel: ':root:not([data-theme="light"])' },
    { at: '(prefers-color-scheme: dark)', sel: ':root[data-contrast="more"]:not([data-theme="light"])' },
    { at: '(prefers-contrast: more)', sel: ':root[data-theme="dark"]' },
    { sel: ':root[data-contrast="more"][data-theme="dark"]' },
  ],
};

/**
 * @param {Map<string, import('./load.mjs').Token>} tokens
 * @returns {string}
 */
export function buildCss(tokens) {
  const nonDensity = [...tokens.values()].filter((t) => !t.path.startsWith('density.'));
  const moded = nonDensity.filter(hasModes);
  const densities = densityBlocks(tokens);

  const out = [
    '/* Nodalia Design Language tokens. Generated by @nodalia/tokens: do not edit. */',
    '',
    ':root {',
    ...nonDensity.map((t) => decl(t, css(rawValue(t, 'light'), t.type, ctxFor(t)))),
    ...[...(densities.get('regular') ?? [])],
    '}',
  ];

  for (const [name, lines] of densities) {
    if (name === 'regular') continue;
    out.push('', `:root[data-density="${name}"] {`, ...lines, '}');
  }

  // Each mode block is complete over every mode-dependent token, so overlapping
  // selectors (system preference + explicit attribute) can never leak values across modes.
  for (const mode of MODES.filter((m) => MODE_CHAIN[m].length > 0)) {
    const body = moded.map((t) => decl(t, css(rawValue(t, mode), t.type, ctxFor(t)))).join('\n');
    for (const { at, sel } of MODE_SELECTORS[mode]) {
      const block = `${sel} {\n${body}\n}`;
      out.push('', at ? `@media ${at} {\n${indent(block)}\n}` : block);
    }
  }

  const transitions = nonDensity.filter((t) => t.type === 'transition');
  const reduced = transitions
    .map((t) => decl(t, css(t.value, t.type, ctxFor(t, { zeroDuration: true }))))
    .join('\n');
  out.push(
    '',
    `@media (prefers-reduced-motion: reduce) {\n  :root:not([data-motion="full"]) {\n${indent(reduced, 2)}\n  }\n}`,
    '',
    `:root[data-motion="reduced"] {\n${reduced}\n}`,
    '',
  );
  return out.join('\n');
}

const indent = (s, n = 1) => s.split('\n').map((l) => '  '.repeat(n) + l).join('\n');
