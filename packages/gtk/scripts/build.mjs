// Generates, for GTK4 / libadwaita apps:
//   dist/nodalia-<mode>.css             libadwaita named colours plus --ndl-color-* variables, per mode
//   dist/nodalia-metrics-<density>.css  spacing, radii, type, motion and component sizes as --ndl-* variables
// Both contain variables only (plus libadwaita's documented named colours); which widget wears which
// value is the app's call, in its own sheet, because widget selectors here would tie NDL to GTK internals.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { MODES, SOURCE_DIR, loadTokens, resolve, cssName, gtkColor } from '@nodalia/tokens/lib';
import { ICONS } from '@nodalia/icons/src';
import { BOLD_STROKE, boldBody } from '@nodalia/icons/bold';

const mapping = Object.entries(JSON.parse(readFileSync(new URL('../mapping.json', import.meta.url), 'utf8')))
  .filter(([k]) => !k.startsWith('$'));
const tokens = loadTokens(SOURCE_DIR);
const dist = new URL('../dist/', import.meta.url).pathname;

export const DENSITIES = [...new Set([...tokens.values()]
  .filter((t) => t.path.startsWith('density.')).map((t) => t.path.split('.')[1]))];

/** A DTCG shadow as a GTK box-shadow value. */
function shadow(path, mode) {
  const v = resolve(tokens, path, mode);
  const part = (x) => (typeof x === 'string' && x.startsWith('{') ? resolve(tokens, x.slice(1, -1), mode) : x);
  const len = (x) => (part(x) === '0px' ? '0' : part(x));
  return `${len(v.offsetX)} ${len(v.offsetY)} ${len(v.blur)} ${len(v.spread)} ${gtkColor(part(v.color))}`;
}

export function gtkCss(mode) {
  const color = (path) => gtkColor(resolve(tokens, path, mode));
  const colorTokens = [...tokens.values()].filter((t) => t.type === 'color');
  return [
    `/* Nodalia Design Language for GTK4 / libadwaita (${mode}). Generated by @nodalia/gtk: do not edit.`,
    ' * Load with Gtk.CssProvider at STYLE_PROVIDER_PRIORITY_APPLICATION after choosing the matching',
    ' * Adw.ColorScheme. Only documented libadwaita named colours are set. */',
    '',
    ...mapping.map(([name, path]) => `@define-color ${name} ${color(path)};`),
    '',
    ':root {',
    ...mapping.map(([name, path]) => `  --${name.replaceAll('_', '-')}: ${color(path)};`),
    ...colorTokens.map((t) => `  ${cssName(t.path)}: ${color(t.path)};`),
    // Elevation lives here, not in the metric sheets: its colour changes with the mode.
    ...[...tokens.values()].filter((t) => t.type === 'shadow').map((t) => `  ${cssName(t.path)}: ${shadow(t.path, mode)};`),
    '}',
    '',
  ].join('\n');
}

/** Metric tokens GTK can use: everything but colours (the mode sheet has those) and composites. */
const METRIC_TYPES = new Set(['dimension', 'fontWeight', 'fontFamily', 'duration', 'cubicBezier']);

/** One token as GTK CSS. Dimensions stay in px: GTK has no root font size to scale rem against. */
export function gtkValue(token) {
  const value = resolve(tokens, token.path, 'light');
  switch (token.type) {
    case 'dimension': return value === '0px' ? '0' : value;
    case 'fontWeight': return String(value);
    case 'duration': return value;
    case 'cubicBezier': return `cubic-bezier(${value.join(', ')})`;
    case 'fontFamily': {
      // GTK knows no system-ui or -apple-system: the platform default closes the list instead.
      const usable = value.filter((f) => !/^(system-ui|-apple-system|ui-monospace|BlinkMacSystemFont|Segoe UI.*|sans-serif|monospace)$/.test(f));
      const generic = token.path.includes('mono') ? 'monospace' : 'sans-serif';
      return [...usable.map((f) => (/\s/.test(f) ? `"${f}"` : f)), generic].join(', ');
    }
    default: throw new Error(`token ${token.path} has type ${token.type}`);
  }
}

/**
 * Metric variables for one density: --ndl-space-*, --ndl-radius-*, --ndl-font-*, --ndl-component-*,
 * and the density's own values as --ndl-density-*. Variables only, no selectors but :root, so the app
 * decides which widget wears which value (AGENTS.md, rule 4). Needs GTK 4.16+ for var().
 */
export function metricsCss(density) {
  const metrics = [...tokens.values()].filter((t) => METRIC_TYPES.has(t.type) && !t.path.startsWith('density.') && !t.path.startsWith('breakpoint.'));
  const own = [...tokens.values()].filter((t) => t.path.startsWith(`density.${density}.`));
  return [
    `/* Nodalia Design Language for GTK4 / libadwaita: metrics, ${density} density. Generated by @nodalia/gtk: do not edit.`,
    ' * Load beside a nodalia-<mode>.css. Defines variables only; requires GTK 4.16 or later. */',
    '',
    ':root {',
    ...metrics.map((t) => `  ${cssName(t.path)}: ${gtkValue(t)};`),
    ...own.map((t) => `  --ndl-density-${t.path.split('.')[2]}: ${gtkValue(t)};`),
    '}',
    '',
  ].join('\n');
}

/**
 * One NDL icon, in the bold style, as a GTK symbolic SVG. GTK recolours symbolic icons through classes rather than
 * currentColor: `foreground-stroke` takes the text colour on the stroke, `foreground-fill` on the
 * fill, and `transparent-fill` keeps an open path from being filled in.
 */
export function gtkSymbolic(name) {
  const element = (part) => {
    const filled = /fill="currentColor"/.test(part);
    const stroked = !/stroke="none"/.test(part);
    const classes = [filled ? 'foreground-fill' : 'transparent-fill', ...(stroked ? ['foreground-stroke'] : [])];
    const width = /stroke-width=/.test(part) ? '' : ` stroke-width="${BOLD_STROKE}"`;
    const paint = `fill="${filled ? 'rgb(0,0,0)' : 'none'}" stroke="${stroked ? 'rgb(0,0,0)' : 'none'}"`
      + (stroked ? `${width} stroke-linecap="round" stroke-linejoin="round"` : '');
    return part
      .replace(/ (fill|stroke)="(currentColor|none)"/g, '')
      .replace(/^<(\w+)/, `<$1 class="${classes.join(' ')}" ${paint}`);
  };
  const body = boldBody(name).map(element).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">${body}</svg>\n`;
}

/** Every file of the Nodalia icon theme: each icon as ndl-<name>-symbolic, then the aliases. */
export function iconTheme() {
  const aliases = Object.entries(JSON.parse(readFileSync(new URL('../icon-aliases.json', import.meta.url), 'utf8')))
    .filter(([k]) => !k.startsWith('$'));
  const files = Object.keys(ICONS).sort((a, b) => a.localeCompare(b, 'en')).map((n) => [`ndl-${n}-symbolic`, n]);
  return [...files, ...aliases.map(([alias, n]) => [alias.replace(/-symbolic$/, '') + '-symbolic', n])]
    .map(([file, n]) => [file, gtkSymbolic(n)]);
}

/** The icon theme as Rust source for the crate, so it builds from git without Node. */
export function iconsRs() {
  const entries = iconTheme().map(([file, svg]) => `    ("${file}", r##"${svg.trim()}"##),`);
  return [
    '// The Nodalia icon theme, from @nodalia/icons and icon-aliases.json. Generated by @nodalia/gtk: do not edit.',
    '',
    '#[rustfmt::skip]',
    `pub(crate) const ICONS: &[(&str, &str)] = &[`,
    ...entries,
    '];',
    '',
  ].join('\n');
}

/** The typefaces nodalia-gtk registers: Sora for display, Inter for the interface. */
export const FONTS = [['sora', 'Sora[wght].ttf'], ['inter', 'Inter[opsz,wght].ttf']];

/** The hand-written widget sheet. It only reads variables, so it is the same for every mode and density. */
export const WIDGETS = readFileSync(new URL('../src/nodalia-gtk.css', import.meta.url), 'utf8');

/** Every stylesheet this package ships, by file name. */
export function allSheets() {
  const sheets = new Map();
  for (const mode of MODES) sheets.set(`nodalia-${mode}.css`, gtkCss(mode));
  for (const density of DENSITIES) sheets.set(`nodalia-metrics-${density}.css`, metricsCss(density));
  sheets.set('nodalia-gtk.css', WIDGETS);
  return sheets;
}

/** The nodalia-gtk crate embeds the sheets; they are committed so it builds from git without Node. */
export const CRATE_CSS = new URL('../crate/src/css/', import.meta.url).pathname;

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(dist, { recursive: true });
  mkdirSync(CRATE_CSS, { recursive: true });
  for (const [name, css] of allSheets()) {
    writeFileSync(join(dist, name), css);
    writeFileSync(join(CRATE_CSS, name), css);
  }
  writeFileSync(new URL('../crate/src/icons_generated.rs', import.meta.url), iconsRs());
  // The fonts travel inside the crate: a Flatpak build vendors this directory alone.
  const fonts = new URL('../../fonts/', import.meta.url).pathname;
  const crateFonts = new URL('../crate/fonts/', import.meta.url).pathname;
  for (const [family, file] of FONTS) {
    mkdirSync(join(crateFonts, family), { recursive: true });
    copyFileSync(join(fonts, family, file), join(crateFonts, family, file));
    copyFileSync(join(fonts, family, 'OFL.txt'), join(crateFonts, family, 'OFL.txt'));
  }
  console.log(`@nodalia/gtk: ${MODES.length} colour, ${DENSITIES.length} metric and 1 widget stylesheet -> dist/ and crate/src/css/; ${iconTheme().length} icons -> crate/src/icons_generated.rs`);
}
