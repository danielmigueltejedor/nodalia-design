// Generates crate/src/tokens.rs: the NDL tokens as Rust constants for the nodalia-theme crate.
// The file is committed so Rust apps can depend on the crate straight from git, without Node.
// A test fails when the committed file no longer matches the tokens.
import { writeFileSync } from 'node:fs';
import { ICONS } from '../../icons/src/icons.mjs';
import { boldBody } from '../../icons/src/bold.mjs';
import { MODES, SOURCE_DIR, DEFAULT_ACCENT, accentSets, loadTokens, resolve, parseHex, px, ms } from '@nodalia/tokens/lib';

const tokens = loadTokens(SOURCE_DIR);
const all = [...tokens.values()];
const snake = (text) => text.replaceAll(/[.-]/g, '_');
const upper = (text) => snake(text).toUpperCase();
const pascal = (text) => text.split(/[.-]/).map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const float = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const rgba = (hex) => {
  const { r, g, b, a } = parseHex(hex);
  return `Rgba::new(${r}, ${g}, ${b}, ${Math.round(a * 255)})`;
};
const shadow = (v) => `Shadow { color: ${rgba(v.color)}, offset_x: ${float(px(v.offsetX))}, offset_y: ${float(px(v.offsetY))}, blur: ${float(px(v.blur))}, spread: ${float(px(v.spread))} }`;

const colors = all.filter((t) => t.type === 'color' && t.path.startsWith('color.'));
const elevations = all.filter((t) => t.type === 'shadow' && t.path.startsWith('elevation.'));
const colorField = (t) => snake(t.path.slice('color.'.length));
const densityNames = [...new Set(all.filter((t) => t.path.startsWith('density.')).map((t) => t.path.split('.')[1]))];
const densityKeys = [...new Set(all.filter((t) => t.path.startsWith('density.')).map((t) => t.path.split('.')[2]))];
const group = (prefix) => all.filter((t) => t.path.startsWith(`${prefix}.`));
const light = (t) => resolve(tokens, t.path, 'light');
const accents = accentSets(tokens, SOURCE_DIR);

function dimensionModule(name, prefix, doc) {
  const items = group(prefix).filter((t) => t.type === 'dimension');
  return [`/// ${doc}`, `pub mod ${name} {`, ...items.map((t) => `    pub const ${upper(t.path.slice(prefix.length + 1))}: f32 = ${float(px(light(t)))};`), '}', ''];
}

export function rustSource() {
  const lines = [
    '// Nodalia Design Language tokens for Rust. Generated by @nodalia/egui: do not edit.',
    '// Regenerate with `npm run build -w @nodalia/egui`.',
    '',
    '/// A colour with straight (not premultiplied) alpha, channels 0-255.',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub struct Rgba {',
    '    pub r: u8,',
    '    pub g: u8,',
    '    pub b: u8,',
    '    pub a: u8,',
    '}',
    '',
    'impl Rgba {',
    '    pub const fn new(r: u8, g: u8, b: u8, a: u8) -> Self {',
    '        Self { r, g, b, a }',
    '    }',
    '}',
    '',
    '/// A drop shadow, in logical pixels.',
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub struct Shadow {',
    '    pub color: Rgba,',
    '    pub offset_x: f32,',
    '    pub offset_y: f32,',
    '    pub blur: f32,',
    '    pub spread: f32,',
    '}',
    '',
    '/// Appearance mode. The high-contrast modes are chosen by the app or the system preference.',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]',
    'pub enum Mode {',
    ...MODES.map((m) => `    ${pascal(m)},`),
    '}',
    '',
    'impl Mode {',
    `    pub const ALL: [Mode; ${MODES.length}] = [${MODES.map((m) => `Mode::${pascal(m)}`).join(', ')}];`,
    '',
    '    /// The token name of the mode, as used by the other NDL adapters.',
    '    pub const fn name(self) -> &\'static str {',
    '        match self {',
    ...MODES.map((m) => `            Mode::${pascal(m)} => "${m}",`),
    '        }',
    '    }',
    '',
    '    pub const fn is_dark(self) -> bool {',
    `        matches!(self, ${MODES.filter((m) => m.startsWith('dark')).map((m) => `Mode::${pascal(m)}`).join(' | ')})`,
    '    }',
    '',
    '    pub const fn is_high_contrast(self) -> bool {',
    `        matches!(self, ${MODES.filter((m) => m.endsWith('-hc')).map((m) => `Mode::${pascal(m)}`).join(' | ')})`,
    '    }',
    '',
    '    pub const fn palette(self) -> &\'static Palette {',
    '        match self {',
    ...MODES.map((m) => `            Mode::${pascal(m)} => &${upper(m)},`),
    '        }',
    '    }',
    '}',
    '',
    '/// Every semantic colour and elevation of one mode.',
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub struct Palette {',
    ...colors.map((t) => `    pub ${colorField(t)}: Rgba,`),
    ...elevations.map((t) => `    pub ${snake(t.path)}: Shadow,`),
    '}',
    '',
  ];
  for (const mode of MODES) {
    lines.push(
      `pub const ${upper(mode)}: Palette = Palette {`,
      ...colors.map((t) => `    ${colorField(t)}: ${rgba(resolve(tokens, t.path, mode))},`),
      ...elevations.map((t) => `    ${snake(t.path)}: ${shadow(resolve(tokens, t.path, mode))},`),
      '};',
      '',
    );
  }
  // App accents: only the colours that differ from the default palette are written.
  const names = [...accents.keys()];
  lines.push(
    '/// The accent of an app. `Nodalia` is the default; the others take the colour of the app icon.',
    '/// Every accent has the luminance of the default one step by step, so contrast is the same.',
    '#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]',
    'pub enum Accent {',
    '    #[default]',
    ...names.map((n) => `    ${pascal(n)},`),
    '}',
    '',
    'impl Accent {',
    `    pub const ALL: [Accent; ${names.length}] = [${names.map((n) => `Accent::${pascal(n)}`).join(', ')}];`,
    '',
    '    /// The name used by the other NDL adapters (`data-accent` on the web).',
    '    pub const fn name(self) -> &\'static str {',
    '        match self {',
    ...names.map((n) => `            Accent::${pascal(n)} => "${n}",`),
    '        }',
    '    }',
    '}',
    '',
    'impl Mode {',
    '    /// The palette of this mode with the accent of an app.',
    '    pub const fn palette_with(self, accent: Accent) -> Palette {',
    '        let mut p = *self.palette();',
    '        match (accent, self) {',
    `            (Accent::${pascal(DEFAULT_ACCENT)}, _) => {}`,
  );
  for (const [name, set] of accents) {
    if (name === DEFAULT_ACCENT) continue;
    for (const mode of MODES) {
      const changed = colors.filter((t) => resolve(set.tokens, t.path, mode) !== resolve(tokens, t.path, mode));
      lines.push(`            (Accent::${pascal(name)}, Mode::${pascal(mode)}) => {`, ...changed.map((t) => `                p.${colorField(t)} = ${rgba(resolve(set.tokens, t.path, mode))};`), '            }');
    }
  }
  lines.push('        }', '        p', '    }', '}', '');
  lines.push(
    '/// Control metrics of one density, in logical pixels.',
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub struct Density {',
    ...densityKeys.map((k) => `    pub ${snake(k)}: f32,`),
    '}',
    '',
    'impl Density {',
    ...densityNames.flatMap((d) => [
      `    pub const ${upper(d)}: Density = Density {`,
      ...densityKeys.map((k) => `        ${snake(k)}: ${float(px(resolve(tokens, `density.${d}.${k}`, 'light')))},`),
      '    };',
    ]),
    '}',
    '',
    ...dimensionModule('space', 'space', 'Spacing scale, in logical pixels.'),
    ...dimensionModule('radius', 'radius', 'Corner radii, in logical pixels. `FULL` means a pill shape.'),
    ...dimensionModule('border_width', 'border-width', 'Border widths, in logical pixels.'),
    ...dimensionModule('font_size', 'font.size', 'Font sizes, in logical pixels.'),
    ...dimensionModule('line_height', 'font.line-height', 'Line heights, in logical pixels.'),
    ...dimensionModule('size', 'size', 'Fixed sizes (icons, targets, panels), in logical pixels.'),
    ...dimensionModule('component', 'component', 'Component metrics, in logical pixels.'),
    '/// Font weights.',
    'pub mod font_weight {',
    ...group('font.weight').map((t) => `    pub const ${upper(t.path.slice('font.weight.'.length))}: u16 = ${light(t)};`),
    '}',
    '',
    '/// Font family stacks, most preferred first. NDL does not ship the fonts.',
    'pub mod font_family {',
    ...group('font.family').map((t) => `    pub const ${upper(t.path.slice('font.family.'.length))}: &[&str] = &[${light(t).map((f) => JSON.stringify(f)).join(', ')}];`),
    '}',
    '',
    '/// Durations in milliseconds. Use `Motion` to honour reduced motion.',
    'pub mod duration {',
    ...group('duration').map((t) => `    pub const ${upper(t.path.slice('duration.'.length))}: u32 = ${ms(light(t))};`),
    '}',
    '',
    '/// Cubic Bézier control points `[x1, y1, x2, y2]`.',
    'pub mod easing {',
    ...group('easing').map((t) => `    pub const ${upper(t.path.slice('easing.'.length))}: [f32; 4] = [${light(t).map(float).join(', ')}];`),
    '}',
    '',
    '/// A motion role: how long a change takes and with which curve.',
    '#[derive(Clone, Copy, Debug, PartialEq)]',
    'pub struct Transition {',
    '    pub duration_ms: u32,',
    '    pub delay_ms: u32,',
    '    pub easing: [f32; 4],',
    '}',
    '',
    '/// Motion roles.',
    'pub mod motion {',
    '    use super::Transition;',
    ...group('motion').map((t) => {
      const v = light(t);
      return `    pub const ${upper(t.path.slice('motion.'.length))}: Transition = Transition { duration_ms: ${ms(v.duration)}, delay_ms: ${ms(v.delay)}, easing: [${v.timingFunction.map(float).join(', ')}] };`;
    }),
    '}',
    '',
  );
  return lines.join('\n');
}

/** crate/src/icons/data.rs: every NDL icon's elements, sorted by name for a binary search. */
export function iconsSource() {
  const raw = (text) => `r#"${text}"#`;
  const list = (items) => `&[${items.join(', ')}]`;
  // Code-unit order, which is the byte order Rust's str comparison uses (names are unique).
  const names = Object.keys(ICONS).sort((a, b) => (a < b ? -1 : 1));
  // The bold body is stored only where it differs; Icon::bold_body falls back to the regular one.
  const same = (a, b) => a.length === b.length && a.every((x, i) => x === b[i]);
  const entry = (name) => {
    const icon = ICONS[name];
    return [
      '    Icon {',
      `        name: ${JSON.stringify(name)},`,
      `        group: ${JSON.stringify(icon.group)},`,
      `        body: ${list(icon.body.map(raw))},`,
      `        bold: ${same(boldBody(name), icon.body) ? '&[]' : list(boldBody(name).map(raw))},`,
      `        accent: ${list((icon.accent ?? []).map(String))},`,
      '    },',
    ].join('\n');
  };
  return [
    '// Generated by packages/egui/scripts/build.mjs from packages/icons/src. Do not edit.',
    'use super::Icon;',
    '',
    `pub(super) static ICONS: [Icon; ${names.length}] = [`,
    ...names.map(entry),
    '];',
    '',
  ].join('\n');
}

export const ICONS_OUTPUT = new URL('../crate/src/icons/data.rs', import.meta.url).pathname;

export const OUTPUT = new URL('../crate/src/tokens.rs', import.meta.url).pathname;

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(OUTPUT, rustSource());
  writeFileSync(ICONS_OUTPUT, iconsSource());
  console.log('@nodalia/egui: tokens.rs, icons/data.rs -> crate/src/');
}
