// Generates dist/Nodalia/{NodaliaTheme.qml,qmldir}: a singleton exposing the tokens to Qt Quick.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { MODES, SOURCE_DIR, loadTokens, resolve, qmlColor, px, ms } from '@nodalia/tokens/lib';

const tokens = loadTokens(SOURCE_DIR);
const camel = (path) => path.split(/[.-]/).map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1))).join('');
const q = JSON.stringify;

const colors = [...tokens.values()].filter((t) => t.type === 'color' && t.path.startsWith('color.'));
const constants = [...tokens.values()].filter((t) => ['space', 'radius', 'border-width', 'size'].includes(t.path.split('.')[0]) && t.type === 'dimension')
  .concat([...tokens.values()].filter((t) => t.path.startsWith('font.size.') || t.path.startsWith('font.line-height.')));
const weights = [...tokens.values()].filter((t) => t.path.startsWith('font.weight.'));
const families = [...tokens.values()].filter((t) => t.path.startsWith('font.family.'));
const durations = [...tokens.values()].filter((t) => t.path.startsWith('duration.'));
const easings = [...tokens.values()].filter((t) => t.path.startsWith('easing.'));
const motion = [...tokens.values()].filter((t) => t.path.startsWith('motion.'));
const densityKeys = [...new Set([...tokens.keys()].filter((p) => p.startsWith('density.regular.')).map((p) => p.split('.')[2]))];
const densityNames = [...new Set([...tokens.keys()].filter((p) => p.startsWith('density.')).map((p) => p.split('.')[1]))];

export function qmlSource() {
  const palettes = MODES.map((m) => `        ${q(m)}: {\n${colors.map((t) => `            ${q(camel(t.path))}: ${q(qmlColor(resolve(tokens, t.path, m)))}`).join(',\n')}\n        }`).join(',\n');
  const densities = densityNames.map((d) => `        ${q(d)}: { ${densityKeys.map((k) => `${q(camel(k))}: ${px(resolve(tokens, `density.${d}.${k}`, 'light'))}`).join(', ')} }`).join(',\n');
  const lines = [
    '// Nodalia Design Language for Qt Quick. Generated by @nodalia/qml: do not edit.',
    'pragma Singleton',
    'import QtQuick',
    '',
    'QtObject {',
    `    /// "light" | "dark" | "light-hc" | "dark-hc". Bind it to the system colour scheme and contrast preference.`,
    '    property string mode: "light"',
    `    /// ${densityNames.map(q).join(' | ')}`,
    '    property string density: "regular"',
    '    /// True when the user asked the system for reduced motion: transitions collapse to 0 ms.',
    '    property bool reducedMotion: false',
    '',
    '    readonly property var palettes: ({',
    palettes,
    '    })',
    '    readonly property var densities: ({',
    densities,
    '    })',
    '',
    ...colors.map((t) => `    readonly property color ${camel(t.path)}: palettes[mode][${q(camel(t.path))}]`),
    '',
    ...densityKeys.map((k) => `    readonly property int ${camel('density.' + k)}: densities[density][${q(camel(k))}]`),
    '',
    ...constants.map((t) => `    readonly property int ${camel(t.path)}: ${px(resolve(tokens, t.path, 'light'))}`),
    ...weights.map((t) => `    readonly property int ${camel(t.path)}: ${resolve(tokens, t.path, 'light')}`),
    ...families.map((t) => `    readonly property string ${camel(t.path)}: ${q(resolve(tokens, t.path, 'light').join(', '))}`),
    ...durations.map((t) => `    readonly property int ${camel(t.path)}: reducedMotion ? 0 : ${ms(resolve(tokens, t.path, 'light'))}`),
    '    // Easing.BezierSpline control points: [c1x, c1y, c2x, c2y, 1, 1]',
    ...easings.map((t) => `    readonly property var ${camel(t.path)}: ${q([...resolve(tokens, t.path, 'light'), 1, 1])}`),
    '    // Motion roles: duration in ms (0 under reduced motion). Pair with the matching easing.',
    ...motion.map((t) => {
      const v = resolve(tokens, t.path, 'light');
      return `    readonly property int ${camel(t.path)}Duration: reducedMotion ? 0 : ${ms(v.duration)}`;
    }),
    '}',
    '',
  ];
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = new URL('../dist/Nodalia/', import.meta.url).pathname;
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'NodaliaTheme.qml'), qmlSource());
  writeFileSync(join(out, 'qmldir'), 'module Nodalia\nsingleton NodaliaTheme 1.0 NodaliaTheme.qml\n');
  console.log('@nodalia/qml: NodaliaTheme.qml -> dist/Nodalia/');
}
